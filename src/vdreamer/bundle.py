"""``vdreamer bundle`` — the offline install set, built on a connected host.

Operator-run, with plain pip (never uv: the plain-pip CI job holds vdreamer to
that). Into ``--out`` (default ``./vdreamer-bundle``):

- ``wheelhouse/`` — ``python -m pip download`` of vdreamer (with the chosen
  extras) plus the operator's agent requirements (``-r``), constrained by the
  release's ``constraints.txt`` (``-c``) so the tested dependency set is what
  ships. pip resolves against a hash-free copy of the pins (hashes in a
  constraints file would force ``--require-hashes`` on the agent requirements);
  every downloaded file of a pinned project is then checked against the
  release's sha256s — the tested artifacts, not just the tested versions.
  ``--platform``/``--python-version`` build for the air-gapped target from a
  different host (binary wheels only, as pip requires).
- ``requirements.lock`` — every file in the wheelhouse as
  ``name==version --hash=sha256:…`` (all of a version's files hashed), for
  ``pip install --no-index --find-links wheelhouse --require-hashes``.
- ``tiktoken/`` — the tiktoken encodings, so token counting never downloads
  them (set ``TIKTOKEN_CACHE_DIR`` to it). Skipped with
  ``--no-tiktoken`` or when tiktoken is not installed here.
- ``fastembed/`` — with ``--models models.yaml``, every fastembed alias
  downloaded into a cache the workers load with ``local_files_only``:
  ship it as the ``fastembed.cache_dir`` (baked into the image or a
  read-only volume).
- ``bundle.json`` — what was bundled, with sha256s; ``INSTALL.txt`` — the
  air-gapped install commands.

This command is the one that *does* reach the network, so it does not force
the offline environment the other commands apply (it clears the HF offline
switches for its own downloads).
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Final

from vdreamer import __version__
from vdreamer.offline import TIKTOKEN_ENCODINGS

DEFAULT_OUT: Final = "vdreamer-bundle"

#: Distribution files pip may leave in a wheelhouse.
_WHEEL: Final = re.compile(
    r"^(?P<name>[^-]+)-(?P<version>[^-]+)(-\d[^-]*)?-[^-]+-[^-]+-[^-]+\.whl$"
)
_SDIST: Final = re.compile(r"^(?P<name>.+)-(?P<version>[^-]+)\.(tar\.gz|zip|tar\.bz2)$")

Runner = Callable[[Sequence[str]], int]


class BundleError(RuntimeError):
    """The bundle could not be built."""


def normalize(name: str) -> str:
    """PEP 503 name normalization (``Foo_Bar.baz`` → ``foo-bar-baz``)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_distribution(filename: str) -> tuple[str, str] | None:
    """``(normalized name, version)`` of a wheel or sdist filename, else ``None``."""
    match = _WHEEL.match(filename) or _SDIST.match(filename)
    if match is None:
        return None
    return normalize(match["name"]), match["version"]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def lock_wheelhouse(wheelhouse: Path) -> str:
    """The hash-pinned ``requirements.lock`` for every distribution in ``wheelhouse``.

    One line per project, ``name==version`` with a ``--hash`` for each of that
    version's files (a wheel and its sdist, or several platform wheels). Two
    versions of one project is an error: pip could not install both.
    """
    projects: dict[str, tuple[str, list[str]]] = {}
    for path in sorted(wheelhouse.iterdir()):
        if not path.is_file():
            continue
        parsed = parse_distribution(path.name)
        if parsed is None:
            continue
        name, version = parsed
        known = projects.get(name)
        if known is not None and known[0] != version:
            raise BundleError(
                f"the wheelhouse holds two versions of {name}: {known[0]} and {version}"
            )
        projects.setdefault(name, (version, []))[1].append(sha256_file(path))
    if not projects:
        raise BundleError(f"no distributions in {wheelhouse}")
    lines = [
        "# Generated by `vdreamer bundle` — install with:",
        "#   pip install --no-index --find-links wheelhouse --require-hashes -r requirements.lock",
    ]
    for name in sorted(projects):
        version, hashes = projects[name]
        pins = " \\\n    ".join(f"--hash=sha256:{digest}" for digest in sorted(set(hashes)))
        lines.append(f"{name}=={version} \\\n    {pins}")
    return "\n".join(lines) + "\n"


_PIN: Final = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?==(?P<version>[^\s;]+)"
)
_HASH: Final = re.compile(r"--hash=sha256:(?P<digest>[0-9a-fA-F]{64})")


@dataclass(frozen=True)
class Constraint:
    """One pinned line of the release ``constraints.txt``."""

    name: str
    version: str
    line: str
    hashes: frozenset[str]


def parse_constraints(text: str) -> dict[str, Constraint]:
    """The pins of a ``uv export``-style constraints file (continuations joined)."""
    logical: list[str] = []
    current = ""
    for raw in text.splitlines():
        stripped = raw.strip()
        if not current and (not stripped or stripped.startswith("#")):
            continue
        if stripped.startswith("#"):
            continue
        if stripped.endswith("\\"):
            current += stripped[:-1] + " "
            continue
        logical.append(current + stripped)
        current = ""
    if current:
        logical.append(current)
    pins: dict[str, Constraint] = {}
    for line in logical:
        requirement = line.split("--hash", 1)[0].strip()
        match = _PIN.match(requirement)
        if match is None:
            continue
        name = normalize(match["name"])
        pins[name] = Constraint(
            name=name,
            version=match["version"],
            line=requirement,
            hashes=frozenset(m["digest"].lower() for m in _HASH.finditer(line)),
        )
    return pins


def unhashed_constraints(pins: dict[str, Constraint]) -> str:
    """The pins without hashes: what pip gets as ``-c`` (hashes there would force
    ``--require-hashes`` on the operator's own, possibly unpinned, requirements)."""
    return "\n".join(pins[name].line for name in sorted(pins)) + "\n"


def verify_against_constraints(wheelhouse: Path, pins: dict[str, Constraint]) -> list[str]:
    """Every downloaded file of a pinned project must match the release's version and
    one of its hashes — the tested artifacts, not merely the tested versions. The problems."""
    problems: list[str] = []
    for path in sorted(wheelhouse.iterdir()):
        parsed = parse_distribution(path.name) if path.is_file() else None
        if parsed is None or parsed[0] not in pins:
            continue
        pin = pins[parsed[0]]
        if parsed[1] != pin.version:
            problems.append(f"{path.name}: version {parsed[1]}, the release pins {pin.version}")
        elif pin.hashes and sha256_file(path) not in pin.hashes:
            problems.append(f"{path.name}: sha256 is not one the release constraints list")
    return problems


@dataclass(frozen=True)
class BundleOptions:
    """What ``vdreamer bundle`` builds."""

    out: Path
    vdreamer: str | None = None
    extras: tuple[str, ...] = ()
    requirements: tuple[str, ...] = ()
    constraints: str | None = None
    platforms: tuple[str, ...] = ()
    python_version: str | None = None
    implementation: str | None = None
    abis: tuple[str, ...] = ()
    index_url: str | None = None
    models: str | None = None
    tiktoken: bool = True
    pip_args: tuple[str, ...] = field(default=())

    def vdreamer_requirement(self) -> str:
        """``vdreamer[extras]==<this version>``, or the ``--vdreamer`` spec/path given."""
        base = self.vdreamer or f"vdreamer=={__version__}"
        if not self.extras:
            return base
        extras = ",".join(sorted(set(self.extras)))
        if "==" in base and "[" not in base:
            name, _, version = base.partition("==")
            return f"{name}[{extras}]=={version}"
        if base.endswith(".whl") or os.sep in base or "/" in base:
            return f"{base}[{extras}]"  # pip accepts extras on a local wheel path
        return base


def pip_download_command(
    options: BundleOptions, requirements_in: Path, constraints: Path | None = None
) -> list[str]:
    """The ``python -m pip download`` invocation (the current interpreter's pip).

    ``constraints`` is the hash-free copy :func:`build_bundle` writes.
    """
    command = [
        sys.executable,
        "-m",
        "pip",
        "download",
        "--disable-pip-version-check",
        "--dest",
        str(options.out / "wheelhouse"),
        "-r",
        str(requirements_in),
    ]
    if constraints is not None:
        command += ["-c", str(constraints)]
    cross = bool(options.platforms or options.python_version or options.abis)
    for platform in options.platforms:
        command += ["--platform", platform]
    if options.python_version:
        command += ["--python-version", options.python_version]
    if options.implementation:
        command += ["--implementation", options.implementation]
    for abi in options.abis:
        command += ["--abi", abi]
    if cross:
        command += ["--only-binary=:all:"]
    if options.index_url:
        command += ["--index-url", options.index_url]
    command += list(options.pip_args)
    return command


def _run(command: Sequence[str]) -> int:
    return subprocess.run(list(command), check=False).returncode


def fetch_tiktoken(target: Path) -> list[str]:
    """Download the tiktoken encodings into ``target``; the names fetched."""
    import tiktoken

    target.mkdir(parents=True, exist_ok=True)
    previous = os.environ.get("TIKTOKEN_CACHE_DIR")
    os.environ["TIKTOKEN_CACHE_DIR"] = str(target)
    try:
        for name in TIKTOKEN_ENCODINGS:
            tiktoken.get_encoding(name)
    finally:
        if previous is None:
            os.environ.pop("TIKTOKEN_CACHE_DIR", None)
        else:
            os.environ["TIKTOKEN_CACHE_DIR"] = previous
    return list(TIKTOKEN_ENCODINGS)


def fetch_fastembed(models_yaml: str, target: Path) -> list[str]:
    """Download every fastembed alias of ``models_yaml`` into ``target``; the aliases."""
    from vdreamer.models import (
        FastembedModelConfig,
        FastembedSettings,
        check_fastembed_files,
        load_models,
    )

    config = load_models(models_yaml)
    aliases = {
        alias: model
        for alias, model in config.aliases.items()
        if isinstance(model, FastembedModelConfig)
    }
    if not aliases:
        return []
    try:
        from fastembed import SparseTextEmbedding, TextEmbedding
        from fastembed.rerank.cross_encoder import TextCrossEncoder
    except ImportError as exc:
        raise BundleError(
            "--models needs fastembed on this host: pip install 'vdreamer[fastembed]'"
        ) from exc
    classes: dict[str, Any] = {
        "embedding": TextEmbedding,
        "sparse": SparseTextEmbedding,
        "rerank": TextCrossEncoder,
    }
    target.mkdir(parents=True, exist_ok=True)
    for name in ("HF_HUB_OFFLINE", "TRANSFORMERS_OFFLINE"):  # this command downloads
        os.environ.pop(name, None)
    for alias, model in sorted(aliases.items()):
        print(f"bundle: fetching fastembed {alias} ({model.model})")
        classes[model.kind](model_name=model.model, cache_dir=str(target), lazy_load=True)
    # Prove the cache is what the workers will see: located offline.
    settings = FastembedSettings(cache_dir=str(target))
    for model in aliases.values():
        check_fastembed_files(model, settings)
    return sorted(aliases)


def _install_text(options: BundleOptions) -> str:
    lines = [
        "vdreamer offline install — on the air-gapped host, no uv needed:",
        "",
        "  python -m venv /opt/vdreamer/venv",
        "  /opt/vdreamer/venv/bin/pip install --no-index --find-links ./wheelhouse \\",
        "      --require-hashes -r requirements.lock",
        "  /opt/vdreamer/venv/bin/vdreamer doctor --offline",
        "",
    ]
    if (options.out / "tiktoken").is_dir():
        lines += ["Ship tiktoken/ and set TIKTOKEN_CACHE_DIR to it.", ""]
    if (options.out / "fastembed").is_dir():
        lines += [
            "Ship fastembed/ (baked into the image or a read-only volume) and point",
            "models.yaml `fastembed.cache_dir` at it.",
            "",
        ]
    return "\n".join(lines)


def build_bundle(options: BundleOptions, *, runner: Runner = _run) -> dict[str, Any]:
    """Build the bundle under ``options.out``; the manifest written as ``bundle.json``."""
    out = options.out
    wheelhouse = out / "wheelhouse"
    wheelhouse.mkdir(parents=True, exist_ok=True)
    requirements_in = out / "requirements.in"
    lines = [options.vdreamer_requirement()]
    for path in options.requirements:
        lines.append(f"-r {Path(path).resolve()}")
    requirements_in.write_text("\n".join(lines) + "\n", encoding="utf-8")

    pins: dict[str, Constraint] = {}
    pip_constraints: Path | None = None
    if options.constraints:
        pins = parse_constraints(Path(options.constraints).read_text(encoding="utf-8"))
        if not pins:
            raise BundleError(f"{options.constraints}: no 'name==version' pins")
        pip_constraints = out / "constraints.pins.txt"
        pip_constraints.write_text(unhashed_constraints(pins), encoding="utf-8")

    command = pip_download_command(options, requirements_in, pip_constraints)
    print("bundle: " + " ".join(command))
    code = runner(command)
    if code != 0:
        raise BundleError(f"pip download failed (exit {code})")
    mismatches = verify_against_constraints(wheelhouse, pins)
    if mismatches:
        raise BundleError(
            "the download does not match the release constraints:\n  " + "\n  ".join(mismatches)
        )

    lock = lock_wheelhouse(wheelhouse)
    (out / "requirements.lock").write_text(lock, encoding="utf-8")

    fetched: dict[str, list[str]] = {"tiktoken": [], "fastembed": []}
    if options.tiktoken:
        import importlib.util

        if importlib.util.find_spec("tiktoken") is not None:
            fetched["tiktoken"] = fetch_tiktoken(out / "tiktoken")
        else:
            print("bundle: tiktoken is not installed here — tiktoken/ skipped")
    if options.models:
        fetched["fastembed"] = fetch_fastembed(options.models, out / "fastembed")

    manifest: dict[str, Any] = {
        "vdreamer_version": __version__,
        "requirement": lines[0],
        "constraints": options.constraints,
        "target": {
            "platforms": list(options.platforms),
            "python_version": options.python_version,
            "implementation": options.implementation,
            "abis": list(options.abis),
        },
        "wheelhouse": {
            path.name: sha256_file(path) for path in sorted(wheelhouse.iterdir()) if path.is_file()
        },
        "tiktoken": fetched["tiktoken"],
        "fastembed": fetched["fastembed"],
    }
    (out / "bundle.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (out / "INSTALL.txt").write_text(_install_text(options), encoding="utf-8")
    return manifest


def run_bundle(options: BundleOptions) -> int:
    """CLI entry point for ``vdreamer bundle``."""
    try:
        manifest = build_bundle(options)
    except BundleError as exc:
        print(f"bundle: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:  # a fetch failed: name it, do not trace back at the operator
        print(f"bundle: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    count = len(manifest["wheelhouse"])
    print(f"[ok] {options.out.as_posix()}/wheelhouse: {count} distribution(s)")
    print(f"[ok] {options.out.as_posix()}/requirements.lock (hash-pinned)")
    if manifest["tiktoken"]:
        print(f"[ok] {options.out.as_posix()}/tiktoken: {', '.join(manifest['tiktoken'])}")
    if manifest["fastembed"]:
        print(f"[ok] {options.out.as_posix()}/fastembed: {', '.join(manifest['fastembed'])}")
    print(f"bundle: done — see {options.out.as_posix()}/INSTALL.txt")
    return 0



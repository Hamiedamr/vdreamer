class SiteInput(pydantic.BaseModel):
    """What the mail worker sends."""

    site_id: str = pydantic.Field(description="The site under review.")
    package: FileRef
    priority: int = 1
    tags: list[str] = []


class SiteAgent(BaseAgent):
    name = "site-check"
    mode = Mode.HEADLESS
    input_schema = SiteInput

    def build(self, ctx: BuildContext) -> Any:  # never built by export-schema
        raise NotImplementedError


class ChatAgent(BaseAgent):
    name = "chat"
    mode = Mode.CHAT

    def build(self, ctx: BuildContext) -> Any:
        raise NotImplementedError


AGENTS: dict[str, BaseAgent] = {"site-check": SiteAgent(), "chat": ChatAgent()}


def test_the_export_is_deterministic_and_self_describing() -> None:
    first = build_export(AGENTS)
    assert first == build_export(AGENTS)  # byte-identical: a release diff is the contract diff
    contract = [path for path in sorted(first) if not path.startswith("conformance/")]
    assert contract == [
        "agents/site-check.input.schema.json",
        "events.schema.json",
        "manifest.json",
        "openapi.json",
        "vdreamer.d.ts",
    ]
    assert "conformance/README.md" in first  # the M11 kit rides the same export
    manifest = json.loads(first["manifest.json"])
    assert manifest["protocol_version"] == PROTOCOL_VERSION == "1.0"
    assert manifest["openapi_version"] == "3.1.0"
    assert manifest["agents"] == {
        "chat": {"mode": "chat", "input_schema": False},
        "site-check": {"mode": "headless", "input_schema": True},
    }
    for path, digest in manifest["files"].items():
        assert hashlib.sha256(first[path]).hexdigest() == digest


def test_openapi_is_valid_3_1_and_what_the_gateway_serves() -> None:
    from openapi_spec_validator import validate

    document = openapi_document(AGENTS)
    validate(document)
    assert "/api/v1/agents/{name}/trigger" in document["paths"]

    from vdreamer.artifacts import InMemoryArtifactStore
    from vdreamer.eventlog import InMemoryEventLog
    from vdreamer.gateway import GatewayBackend, GatewaySettings, create_app
    from vdreamer.interrupts import InMemoryInterruptStore
    from vdreamer.queue import InMemoryRunQueue
    from vdreamer.threads import InMemoryThreadStore

    log = InMemoryEventLog()
    app = create_app(
        GatewayBackend(
            agents=AGENTS, queue=InMemoryRunQueue(), threads=InMemoryThreadStore(),
            event_reader=log, event_writer=log, hub=log.hub,
            interrupts=InMemoryInterruptStore(), artifacts=InMemoryArtifactStore(),
        ),
        GatewaySettings(tokens=("another-token-0123456789",)),
    )
    with TestClient(app) as client:
        served = client.get("/api/v1/openapi.json").json()
    assert served == document


def test_event_and_input_schemas() -> None:
    files = build_export(AGENTS)
    assert json.loads(files["events.schema.json"]) == json.loads(
        json.dumps(event_json_schema(), sort_keys=True)
    )
    schema = json.loads(files["agents/site-check.input.schema.json"])
    assert schema["$schema"] == "https://json-schema.org/draft/2020-12/schema"
    assert schema["required"] == ["site_id", "package"]
    assert "FileRef" in schema["$defs"]

    import jsonschema

    jsonschema.Draft202012Validator.check_schema(schema)
    good = {"site_id": "S1", "package": {"object_key": "inputs/x.zip"}}
    jsonschema.validate(good, schema)
    with pytest.raises(jsonschema.ValidationError):
        jsonschema.validate({"package": {"object_key": "inputs/x.zip"}}, schema)


def _balanced(ts: str) -> bool:
    depth = 0
    for char in re.sub(r'"[^"\n]*"', '""', ts):
        depth += {"{": 1, "}": -1}.get(char, 0)
        if depth < 0:
            return False
    return depth == 0


def test_the_typescript_declarations() -> None:
    ts = build_export(AGENTS)["vdreamer.d.ts"].decode()
    assert ts.startswith("// Generated by `vdreamer export-schema`")
    assert _balanced(ts)
    assert 'export type ProtocolVersion = "1.0";' in ts
    for event in EventType:
        assert f'| "{event.value}"' in ts
        assert f'Envelope<"{event.value}", Events.' in ts
    # Every payload the union names is declared in the Events namespace.
    events_block = ts.split("export declare namespace Events {", 1)[1].split("\n}\n", 1)[0]
    for name in set(re.findall(r"Events\.(\w+)>", ts)):
        assert f"export type {name} = " in events_block
    assert "export declare namespace Api {" in ts and "export type RunCreated = {" in ts
    agents = ts.split("export declare namespace Agents {", 1)[1]
    assert "export namespace site_check {" in agents
    assert "export type Input = {" in agents and "site_id: string;" in agents
    assert "package: FileRef;" in agents and "export type FileRef = {" in agents
    assert "priority?: number;" in agents and "tags?: string[];" in agents
    assert "/** The site under review. */" in agents
    assert "namespace chat" not in agents  # no input_schema, nothing to type
    assert re.search(r":\s*any\b|\bany\[\]|<any>", ts) is None  # never `any`: unknown at worst


@pytest.mark.parametrize(
    ("schema", "expected"),
    [
        ({"type": "string"}, "string"),
        ({"type": "integer"}, "number"),
        ({"type": ["string", "null"]}, "string | null"),
        ({"const": "x"}, '"x"'),
        ({"enum": ["a", 1, None, True]}, '"a" | 1 | null | true'),
        ({"anyOf": [{"type": "string"}, {"type": "null"}]}, "string | null"),
        ({"anyOf": [{"type": "string"}, {}]}, "unknown"),
        ({"allOf": [{"$ref": "#/$defs/A"}, {"$ref": "#/components/schemas/B"}]}, "A & B"),
        ({"$ref": "#/definitions/Foo-Bar"}, "Foo_Bar"),
        ({"$ref": "https://elsewhere/x.json"}, "unknown"),
        ({"type": "array", "items": {"anyOf": [{"type": "string"}, {"type": "number"}]}},
         "(string | number)[]"),
        ({"type": "array", "prefixItems": [{"type": "string"}, {"type": "number"}]},
         "[string, number]"),
        ({"type": "array"}, "unknown[]"),
        ({"type": "object"}, "Record<string, unknown>"),
        ({"type": "object", "additionalProperties": False}, "Record<string, never>"),
        ({"type": "object", "additionalProperties": {"type": "number"}},
         "{\n  [key: string]: number;\n}"),
        ({"type": "object", "properties": {"a-b": {"type": "string"}}, "required": ["a-b"],
          "additionalProperties": False}, '{\n  "a-b": string;\n}'),
        (True, "unknown"),
        ({"not": {"type": "string"}}, "unknown"),
    ],
)
def test_to_ts(schema: Any, expected: str) -> None:
    assert to_ts(schema) == expected


def test_declarations_and_names() -> None:
    assert type_name("Model-Input") == "Model_Input" and type_name("3d") == "_3d"
    body = declarations(
        {"B": {"type": "string", "description": "two\nlines"}, "A": {"type": "number"}},
        indent="  ",
    )
    assert body.index("export type A") < body.index("export type B")  # sorted
    assert "  /**\n   * two\n   * lines\n   */\n  export type B = string;" in body
    wrapped = namespace("ns", body)
    assert wrapped.startswith("export declare namespace ns {\n") and wrapped.endswith("}\n")


def test_the_cli_writes_and_replaces_an_export(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.syspath_prepend(str(Path(__file__).resolve().parents[2] / "examples" / "smoke"))
    out = tmp_path / "schema"
    write_export({"agents/gone.input.schema.json": b"{}"}, out)  # an older export's leftovers
    assert main(["export-schema", "--agent", "pinger:agent", "--out", str(out)]) == 0
    assert (out / "agents" / "pinger.input.schema.json").is_file()
    assert not (out / "agents" / "gone.input.schema.json").exists()
    assert (out / "vdreamer.d.ts").read_text(encoding="utf-8").count("namespace pinger") == 1
    assert "agents: pinger" in capsys.readouterr().out

    # No agent at all: the generic contract alone.
    bare = tmp_path / "bare"
    assert main(["export-schema", "--out", str(bare)]) == 0
    assert json.loads((bare / "manifest.json").read_text(encoding="utf-8"))["agents"] == {}
    assert main(["export-schema", "--agent", "no.such:agent", "--out", str(bare)]) == 1
